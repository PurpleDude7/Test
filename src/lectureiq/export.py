"""Export a StudyPack as a Markdown study guide or an Anki-importable flashcard CSV."""

from __future__ import annotations

import csv
import io

from lectureiq.models import StudyPack
from lectureiq.transcript import format_ts


def _at(start: float | None) -> str:
    return f" ({format_ts(start)})" if start is not None else ""


def to_markdown(pack: StudyPack) -> str:
    out = [f"# {pack.title}", "", f"> {pack.tldr}", ""]
    if pack.sections:
        out += ["## Outline", ""]
        for i, s in enumerate(pack.sections, 1):
            out += [f"{i}. **{s.heading}**{_at(s.start)}: {s.summary}"]
        out.append("")
    if pack.key_points:
        out += ["## Key points", ""] + [f"- {p.text}" for p in pack.key_points] + [""]
    if pack.terms:
        out += ["## Glossary", ""] + [f"- **{t.term}**: {t.definition}" for t in pack.terms]
        out.append("")
    if pack.flashcards:
        out += ["## Flashcards", ""]
        out += [f"- **Q:** {c.front}  \n  **A:** {c.back}" for c in pack.flashcards] + [""]
    if pack.quiz:
        out += ["## Quiz", ""]
        for i, q in enumerate(pack.quiz, 1):
            out.append(f"{i}. {q.question}")
            out += [f"   - {chr(65 + j)}. {opt}" for j, opt in enumerate(q.options)]
        out += ["", "### Answers", ""]
        for i, q in enumerate(pack.quiz, 1):
            why = f": {q.explanation}" if q.explanation else ""
            out.append(f"{i}. **{chr(65 + q.answer)}**{why}")
        out.append("")
    out.append(f"_Generated by LectureIQ ({pack.engine} engine)._")
    return "\n".join(out) + "\n"


def flashcards_csv(pack: StudyPack) -> str:
    """Two columns, front and back, no header: Anki's File > Import accepts it as is."""
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    for card in pack.flashcards:
        writer.writerow([card.front, card.back])
    return buf.getvalue()
